inline uint8_t xtime(uint8_t x) { return (uint8_t)((x << 1) ^ ((x & 0x80) ? 0x1B : 0x00)); }

void expand_key(const uint8_t key[16], uint8_t rk[176]) {
  std::memcpy(rk, key, 16);
  uint8_t rc = 1;
  for (int i = 16; i < 176; i += 16) {
    uint8_t t[4];
    std::memcpy(t, rk + i - 4, 4);
    // RotWord + SubWord + Rcon
    uint8_t tmp = t[0];
    t[0] = (uint8_t)(kSbox[t[1]] ^ rc);
    t[1] = kSbox[t[2]];
    t[2] = kSbox[t[3]];
    t[3] = kSbox[tmp];
    rc = xtime(rc);
    for (int j = 0; j < 4; ++j) rk[i + j] = rk[i - 16 + j] ^ t[j];
    for (int j = 4; j < 16; ++j) rk[i + j] = rk[i - 16 + j] ^ rk[i + j - 4];
  }
}

void encrypt_with_rk(const uint8_t rk[176], const uint8_t in[16], uint8_t out[16]) {
  uint8_t s[16];
  std::memcpy(s, in, 16);
  // AddRoundKey(0)
  for (int i = 0; i < 16; ++i) s[i] ^= rk[i];
  for (int round = 1; round <= 10; ++round) {
    // SubBytes
    for (int i = 0; i < 16; ++i) s[i] = kSbox[s[i]];
    // ShiftRows
    uint8_t t;
    t = s[1]; s[1] = s[5]; s[5] = s[9]; s[9] = s[13]; s[13] = t;
    t = s[2]; s[2] = s[10]; s[10] = t; t = s[6]; s[6] = s[14]; s[14] = t;
    t = s[15]; s[15] = s[11]; s[11] = s[7]; s[7] = s[3]; s[3] = t;
    if (round < 10) {
      // MixColumns
      for (int c = 0; c < 4; ++c) {
        uint8_t* p = s + c * 4;
        uint8_t a0 = p[0], a1 = p[1], a2 = p[2], a3 = p[3];
        p[0] = (uint8_t)(xtime(a0) ^ (xtime(a1) ^ a1) ^ a2 ^ a3);
        p[1] = (uint8_t)(a0 ^ xtime(a1) ^ (xtime(a2) ^ a2) ^ a3);
        p[2] = (uint8_t)(a0 ^ a1 ^ xtime(a2) ^ (xtime(a3) ^ a3));
        p[3] = (uint8_t)((xtime(a0) ^ a0) ^ a1 ^ a2 ^ xtime(a3));
      }
    }
    // AddRoundKey
    for (int i = 0; i < 16; ++i) s[i] ^= rk[round * 16 + i];
  }
  std::memcpy(out, s, 16);
}

void shift_left_one(uint8_t v[16]) {
  uint8_t carry = 0;
  for (int i = 15; i >= 0; --i) {
    uint8_t next = (uint8_t)(v[i] >> 7);
    v[i] = (uint8_t)((v[i] << 1) | carry);
    carry = next;
  }
}

