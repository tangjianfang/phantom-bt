void aes128_encrypt_block(const uint8_t key[16], const uint8_t in[16], uint8_t out[16]) {
  uint8_t rk[176];
  expand_key(key, rk);
  encrypt_with_rk(rk, in, out);
}

void aes_cmac(const uint8_t key[16], const uint8_t* msg, size_t n, uint8_t out[16]) {
  uint8_t rk[176];
  expand_key(key, rk);
  // 子密钥 L = AES(K, 0)
  uint8_t L[16] = {0};
  encrypt_with_rk(rk, L, L);
  uint8_t k1[16], k2[16];
  std::memcpy(k1, L, 16);
  shift_left_one(k1);
  if (L[0] & 0x80) k1[15] ^= 0x87;
  std::memcpy(k2, k1, 16);
  shift_left_one(k2);
  if (k1[0] & 0x80) k2[15] ^= 0x87;

  // 分块：total 块 = 前 total-1 块走 CBC-MAC + 末块异或子密钥（RFC 4493 §2.3）
  uint8_t m_last[16];
  uint8_t x[16] = {0}, y[16];
  bool complete = (n > 0) && (n % 16 == 0);
  size_t total = complete ? n / 16 : (n + 15) / 16;
  if (complete) {
    for (int i = 0; i < 16; ++i) m_last[i] = msg[n - 16 + i] ^ k1[i];
  } else {
    size_t last_off = (n / 16) * 16;  // 末块起点（n=0 时为 0 → 填充块）
    for (int i = 0; i < 16; ++i) {
      uint8_t b = 0;
      if (last_off + (size_t)i < n) b = msg[last_off + i];
      else if (last_off + (size_t)i == n) b = 0x80;
      m_last[i] = b ^ k2[i];
    }
  }
  for (size_t b = 0; total > 0 && b < total - 1; ++b) {
    for (int i = 0; i < 16; ++i) y[i] = x[i] ^ msg[b * 16 + i];
    encrypt_with_rk(rk, y, x);
  }
  // 末块
  for (int i = 0; i < 16; ++i) y[i] = x[i] ^ m_last[i];
  encrypt_with_rk(rk, y, out);
}

